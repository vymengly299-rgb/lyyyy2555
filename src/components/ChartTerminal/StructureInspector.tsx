import React, { useState } from 'react';
import { AssetSummary, StructureAnnotation, TradeSignal } from '../../types';
import { 
  ShieldCheck, 
  Cpu, 
  Flame, 
  Layers, 
  ArrowUpRight, 
  ArrowDownRight, 
  CheckCircle2, 
  Copy, 
  Check, 
  Sliders, 
  Sparkles,
  ExternalLink
} from 'lucide-react';
import { soundManager } from '../../utils/audio';

interface StructureInspectorProps {
  asset: AssetSummary;
  structure: StructureAnnotation[];
  activeSignal?: TradeSignal;
  onOpenSignalModal?: (signal: TradeSignal) => void;
  onOpenWebhookModal?: () => void;
}

export const StructureInspector: React.FC<StructureInspectorProps> = ({
  asset,
  structure,
  activeSignal,
  onOpenSignalModal,
  onOpenWebhookModal,
}) => {
  const [copied, setCopied] = useState(false);

  const copySignalText = () => {
    if (!activeSignal) return;
    soundManager.playClick();
    const text = `🎯 [STRUCT AI SIGNAL] ${activeSignal.pair} ${activeSignal.direction}
Pattern: ${activeSignal.patternLabel}
Entry: ${activeSignal.entryPrice}
Stop Loss: ${activeSignal.stopLoss}
TP1: ${activeSignal.tp1} | TP2: ${activeSignal.tp2} | TP3: ${activeSignal.tp3}
R:R: 1:${activeSignal.riskReward} | AI Score: ${activeSignal.confidence}%
Generated by StructAI Trading Engine`;
    navigator.clipboard.writeText(text);
    setCopied(true);
    setTimeout(() => setCopied(false), 2000);
  };

  return (
    <div className="flex flex-col bg-dark-900 border border-slate-800 rounded-2xl p-4 h-full shadow-xl">
      {/* Header */}
      <div className="flex items-center justify-between pb-3 border-b border-slate-800">
        <div className="flex items-center space-x-2">
          <div className="w-8 h-8 rounded-lg bg-cyan-500/10 border border-cyan-500/30 flex items-center justify-center text-cyan-400">
            <Cpu className="w-4 h-4" />
          </div>
          <div>
            <h3 className="text-sm font-bold text-white flex items-center space-x-1">
              <span>Structure Engine</span>
              <span className="text-[10px] px-1.5 py-0.2 rounded bg-cyan-500/20 text-cyan-300 font-mono">v4.2</span>
            </h3>
            <p className="text-[11px] text-slate-400">Smart Money Analysis for {asset.symbol}</p>
          </div>
        </div>

        <div className="text-right">
          <span className="text-[10px] font-mono text-slate-400 block">AI Score</span>
          <span className="text-base font-extrabold text-cyan-400 font-mono">{asset.aiScore}/100</span>
        </div>
      </div>

      {/* Structural Bias Bar */}
      <div className="my-3 p-3 rounded-xl bg-dark-950 border border-slate-800/80">
        <div className="flex items-center justify-between text-xs mb-1.5">
          <span className="text-slate-400 font-medium">Dominant Structural Bias</span>
          <span className={`font-bold uppercase tracking-wider text-xs px-2 py-0.5 rounded ${
            asset.structureBias === 'BULLISH' 
              ? 'bg-emerald-500/15 text-emerald-400 border border-emerald-500/30' 
              : 'bg-rose-500/15 text-rose-400 border border-rose-500/30'
          }`}>
            {asset.structureBias}
          </span>
        </div>

        {/* Progress confluence meter */}
        <div className="w-full bg-slate-800 h-2 rounded-full overflow-hidden flex">
          <div 
            className={`h-full rounded-full transition-all duration-500 ${
              asset.structureBias === 'BULLISH' ? 'bg-gradient-to-r from-cyan-400 to-emerald-400' : 'bg-gradient-to-r from-amber-400 to-rose-500'
            }`}
            style={{ width: `${asset.aiScore}%` }}
          />
        </div>
        <div className="flex justify-between items-center text-[10px] text-slate-500 mt-1">
          <span>Institutional Absorption</span>
          <span className="text-cyan-400 font-mono">99.4% Order Flow Precision</span>
        </div>
      </div>

      {/* Detected SMC Patterns / Annotations list */}
      <div className="flex-1 overflow-y-auto space-y-2 pr-1 my-1">
        <div className="text-[11px] font-bold text-slate-400 uppercase tracking-wider flex items-center justify-between">
          <span>Active SMC Key Levels</span>
          <span className="text-slate-500 text-[10px]">{structure.length} detected</span>
        </div>

        {structure.map(ann => (
          <div 
            key={ann.id}
            className="p-2.5 rounded-lg bg-dark-850/80 border border-slate-800/70 hover:border-cyan-500/30 transition-all flex items-center justify-between text-xs group"
          >
            <div className="flex items-center space-x-2.5">
              <span className={`w-2 h-2 rounded-full ${
                ann.type === 'BOS' ? 'bg-cyan-400 shadow-sm shadow-cyan-400/50' :
                ann.type === 'ORDER_BLOCK' ? 'bg-emerald-400 shadow-sm shadow-emerald-400/50' :
                ann.type === 'FVG' ? 'bg-amber-400' : 'bg-purple-400'
              }`} />
              <div>
                <p className="text-white font-medium text-xs leading-none">{ann.label}</p>
                <p className="text-[10px] text-slate-400 mt-1 font-mono">
                  {ann.type} • {ann.timeframe} • {ann.mitigated ? 'Mitigated' : 'Fresh Zone'}
                </p>
              </div>
            </div>

            <div className="text-right">
              <span className="font-mono text-xs font-semibold text-slate-200 block">
                {ann.price.toFixed(asset.basePriceDecimals)}
              </span>
              {ann.secondaryPrice && (
                <span className="text-[10px] text-slate-500 font-mono block">
                  - {ann.secondaryPrice.toFixed(asset.basePriceDecimals)}
                </span>
              )}
            </div>
          </div>
        ))}
      </div>

      {/* Active Signal Preview Card */}
      {activeSignal && (
        <div className="mt-3 pt-3 border-t border-slate-800">
          <div className="p-3 rounded-xl bg-gradient-to-b from-dark-850 to-dark-950 border border-cyan-500/20">
            <div className="flex items-center justify-between mb-2">
              <div className="flex items-center space-x-1.5">
                <Sparkles className="w-3.5 h-3.5 text-cyan-400" />
                <span className="text-xs font-bold text-white">Live Signal Setup</span>
              </div>
              <span className={`text-[10px] font-bold px-2 py-0.5 rounded-full ${
                activeSignal.direction === 'LONG' ? 'bg-emerald-500/20 text-emerald-300' : 'bg-rose-500/20 text-rose-300'
              }`}>
                {activeSignal.direction} 1:{activeSignal.riskReward} R:R
              </span>
            </div>

            <div className="grid grid-cols-2 gap-2 text-[11px] font-mono mb-2.5">
              <div className="bg-dark-900/80 p-1.5 rounded border border-slate-800">
                <span className="text-slate-500 block text-[9px]">ENTRY</span>
                <span className="text-cyan-400 font-semibold">{activeSignal.entryPrice.toFixed(asset.basePriceDecimals)}</span>
              </div>
              <div className="bg-dark-900/80 p-1.5 rounded border border-slate-800">
                <span className="text-slate-500 block text-[9px]">STOP LOSS</span>
                <span className="text-rose-400 font-semibold">{activeSignal.stopLoss.toFixed(asset.basePriceDecimals)}</span>
              </div>
              <div className="bg-dark-900/80 p-1.5 rounded border border-slate-800">
                <span className="text-slate-500 block text-[9px]">TARGET 1</span>
                <span className="text-emerald-400 font-semibold">{activeSignal.tp1.toFixed(asset.basePriceDecimals)}</span>
              </div>
              <div className="bg-dark-900/80 p-1.5 rounded border border-slate-800">
                <span className="text-slate-500 block text-[9px]">TARGET 3 (RUNNER)</span>
                <span className="text-emerald-300 font-semibold">{activeSignal.tp3.toFixed(asset.basePriceDecimals)}</span>
              </div>
            </div>

            <div className="flex items-center space-x-2">
              <button
                onClick={copySignalText}
                className="flex-1 flex items-center justify-center space-x-1 text-xs py-1.5 bg-slate-800 hover:bg-slate-700 text-slate-200 font-medium rounded-lg transition"
              >
                {copied ? <Check className="w-3.5 h-3.5 text-emerald-400" /> : <Copy className="w-3.5 h-3.5" />}
                <span>{copied ? 'Copied' : 'Copy Parameters'}</span>
              </button>

              {onOpenSignalModal && (
                <button
                  onClick={() => {
                    soundManager.playClick();
                    onOpenSignalModal(activeSignal);
                  }}
                  className="px-2.5 py-1.5 bg-cyan-500/20 hover:bg-cyan-500/30 text-cyan-300 rounded-lg text-xs font-semibold border border-cyan-500/40 transition flex items-center"
                >
                  <span>Plan</span>
                  <ArrowUpRight className="w-3.5 h-3.5 ml-1" />
                </button>
              )}
            </div>
          </div>
        </div>
      )}

      {/* Integration Webhook Trigger */}
      <div className="mt-3 flex items-center justify-between text-xs text-slate-400 pt-2 border-t border-slate-800/60">
        <span className="text-[11px] flex items-center">
          <ShieldCheck className="w-3.5 h-3.5 text-emerald-400 mr-1" />
          Verified AI Confluence
        </span>
        {onOpenWebhookModal && (
          <button
            onClick={() => {
              soundManager.playClick();
              onOpenWebhookModal();
            }}
            className="text-[11px] text-cyan-400 hover:text-cyan-300 hover:underline flex items-center font-medium"
          >
            <span>Webhook / PineScript</span>
            <ExternalLink className="w-3 h-3 ml-1" />
          </button>
        )}
      </div>
    </div>
  );
};
